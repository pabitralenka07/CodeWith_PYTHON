# All arithmetic operators

a = 10
b = 5

print (a + b)
print (a - b)
print (a * b)
print (a / b)
print (a % b) #Remainder
print (a ** b) #a ^ b

# Relational operators
print (a < b)
print (a > b)
print (a == b)
print (a != b)
print (a >= b)
print (a <= b)
print (a // b) # ' // ' -> Floor division 

# Assignment operator
a = 20
